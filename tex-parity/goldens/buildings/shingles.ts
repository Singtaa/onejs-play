import { tex } from "oj"

const { blend, blur, channelMath, channelShuffle, curvature, directionalWarp, gradientMap, hslAdjust, levels, noise, normalMap, slopeBlur, tileGrid } = tex.canvas(256)

const rows = tileGrid({ columns: 12, rows: 7, jointWidth: 0.1, bevel: 0.06, seed: 31, offsetJitter: 0.35, lengthJitter: 0.45, heightJitter: 0.15, bitDepth: "32" })
const rowsRandom = channelShuffle(rows.random, { outG: "r", outB: "r", outA: "1" })
const rowsV = channelShuffle(rows.uv, { outR: "g", outB: "g", outA: "1" })
const lapRamp = levels(rowsV, { gamma: 0.8, outputBlack: 0.35 })
const shingleFace = levels(rows.image, { inputWhite: 0.6 })
const lapped = blend(shingleFace, lapRamp, "multiply")
const buttNoise = noise("perlin", { scale: 24, tile: true, seed: 701, octaves: 2, scaleY: 7 })
const raggedButts = directionalWarp(lapped, buttNoise, { angle: 90, intensity: 3, edges: "wrap" })
const grain = noise("perlin", { scale: 40, fractal: "ridged", tile: true, seed: 702, octaves: 2, persistence: 0.45, bitDepth: "32", scaleY: 3 })
const grainLines = levels(grain, { inputBlack: 0.78, inputWhite: 0.95 })
const grooveDepth = levels(grainLines, { outputWhite: 0.1 })
const grainGrooves = channelMath(raggedButts, grooveDepth, "subtract")
const wearNoise = noise("perlin", { scale: 12, tile: true, seed: 703, octaves: 3 })
const worn = slopeBlur(grainGrooves, wearNoise, "min", { intensity: 1.5, edges: "wrap" })
const weathering = gradientMap(rowsRandom, { colors: [{ position: 0, color: "#5e3e24" }, { position: 0.12, color: "#6e4a2c" }, { position: 0.4, color: "#7a5a3c" }, { position: 0.65, color: "#80705e" }, { position: 0.85, color: "#8a8478" }, { position: 1, color: "#9a9488" }] })
const silverNoise = noise("perlin", { scale: 3, tile: true, seed: 704, octaves: 3 })
const silverDrift = levels(silverNoise, { inputBlack: 0.4, inputWhite: 0.8 })
const grainInk = gradientMap(grainLines, { colors: [{ position: 0, color: "#ffffff" }, { position: 1, color: "#6a5040" }] })
const heightSmoothed = blur(worn, { radius: 0.7, edges: "wrap" })
const colourFromHeight = gradientMap(heightSmoothed, { colors: [{ position: 0, color: "#1e140c" }, { position: 0.2, color: "#3a2a1c" }, { position: 0.45, color: "#6a5440" }, { position: 0.75, color: "#8a735a" }, { position: 1, color: "#a08a6e" }] })
const pieceTone = gradientMap(rowsRandom, { colors: [{ position: 0, color: "#606060" }, { position: 0.5, color: "#808080" }, { position: 1, color: "#9a9a9a" }] })
const tonePerPiece = blend(colourFromHeight, pieceTone, "softLight", { opacity: 0.5 })
const drift = noise("perlin", { scale: 2, tile: true, seed: 705, octaves: 3 })
const driftHues = gradientMap(drift, { colors: [{ position: 0, color: "#7a5a3a" }, { position: 1, color: "#84827a" }] })
const hueDrift = blend(tonePerPiece, driftHues, "color", { opacity: 0.25 })
const valueDrift = blend(hueDrift, drift, "softLight", { opacity: 0.15 })
const paintedMarks = blend(valueDrift, grainInk, "multiply", { opacity: 0.6 })
const cavitySoft = blur(heightSmoothed, { radius: 3, edges: "wrap" })
const cavity = levels(cavitySoft, { outputBlack: 0.2 })
const cavityColour = gradientMap(cavity, { colors: [{ position: 0, color: "#24160c" }, { position: 1, color: "#ffffff" }] })
const paintedCavity = blend(paintedMarks, cavityColour, "multiply", { opacity: 0.5 })
const curvature2 = curvature(heightSmoothed, "convex", { intensity: 1.2, edges: "wrap" })
const edgeMask = levels(curvature2, { inputBlack: 0.05, inputWhite: 0.6 })
const edgeLight = gradientMap(edgeMask, { colors: [{ position: 0, color: "#000000" }, { position: 1, color: "#f0dcc0" }] })
const wornEdges = blend(paintedCavity, edgeLight, "screen", { opacity: 0.22 })
const saturate = hslAdjust(wornEdges)
const normalOpenGL = normalMap(heightSmoothed, { strength: 2, flipY: true, smoothRadius: 1, edges: "wrap" })
const weatheredHue = blend(saturate, weathering, "color", { opacity: 0.75 })
const silver = gradientMap(silverDrift, { colors: [{ position: 0, color: "#808080" }, { position: 1, color: "#a0a0a0" }] })
const silveredPatches = blend(weatheredHue, silver, "softLight", { opacity: 0.4 })
export const shingles = silveredPatches
export const shinglesNormal = normalOpenGL
