import { tex } from "oj"

const { alphaMerge, blend, blur, channelMath, curvature, gradient, gradientMap, hslAdjust, invert, levels, noise, normalMap, scatter, solidColor, warp } = tex.canvas(256, { height: 512 })

const knotDome = gradient("radial", { colors: [{ position: 0, color: "#ffffff" }, { position: 1, color: "#000000" }], width: 26, height: 40 })
const knotNoise = noise("perlin", { scale: 3, seed: 401, octaves: 2, width: 26, height: 40, scaleY: 4.615384615384616 })
const knotUneven = warp(knotDome, knotNoise, { strength: 3.12, edges: "clamp" })
const knotRingAtMark = solidColor("#595959ff")
const knotRingAt = blend(knotUneven, knotRingAtMark, "difference")
const knotRingBand = levels(knotRingAt, { inputWhite: 0.12 })
const knotRingMark = invert(knotRingBand)
const knotCoreMark = levels(knotUneven, { inputBlack: 0.6, inputWhite: 0.8 })
const knotMark = blend(knotRingMark, knotCoreMark, "lighten")
const knotCut = levels(knotUneven, { inputBlack: 0.05, inputWhite: 0.15 })
const knotStamp = alphaMerge(knotMark, knotCut)
const knots = scatter(knotStamp, { count: 3, seed: 402, scaleMin: 0.8, scaleMax: 1.3, rotationRange: 10, opacityMin: 1, edges: "wrap" })
const knotsUnder = solidColor("#000000ff")
const knotsOn000000ff = blend(knotsUnder, knots.image)
const knotSwirlField = blur(knotsOn000000ff, { radius: 10, edges: "wrap" })
const grainLines = noise("perlin", { scale: 9, fractal: "ridged", tile: true, seed: 403, octaves: 2, persistence: 0.4, bitDepth: "32", scaleY: 1 })
const grainWave = noise("perlin", { scale: 2, tile: true, seed: 404, octaves: 2, scaleY: 3 })
const grainWaving = warp(grainLines, grainWave, { edges: "wrap" })
const grainRoundKnots = warp(grainWaving, knotSwirlField, { strength: 14, edges: "wrap" })
const grainLinesCut = levels(grainRoundKnots, { inputBlack: 0.86, inputWhite: 0.95 })
const fibre = noise("perlin", { scale: 40, tile: true, seed: 405, octaves: 2, scaleY: 3 })
const splitLens = gradient("radial", { colors: [{ position: 0, color: "#ffffff" }, { position: 1, color: "#000000" }], width: 22, height: 300 })
const splitBend = noise("perlin", { scale: 2, seed: 406, octaves: 2, width: 22, height: 300, scaleY: 27.272727272727273 })
const splitBent = warp(splitLens, splitBend, { strength: 3, edges: "clamp" })
const splitCore = levels(splitBent, { inputBlack: 0.35, inputWhite: 0.7 })
const splitCut = levels(splitBent, { inputBlack: 0.3, inputWhite: 0.45 })
const splitStamp = alphaMerge(splitCore, splitCut)
const splits = scatter(splitStamp, { count: 4, seed: 407, scaleMin: 0.7, scaleMax: 1.2, rotationRange: 3, opacityMin: 1, edges: "wrap" })
const splitsUnder = solidColor("#000000ff")
const splitsOn000000ff = blend(splitsUnder, splits.image)
const splitLips = blur(splitsOn000000ff, { radius: 2, edges: "wrap" })
const hewnSwells = noise("perlin", { scale: 4, tile: true, seed: 408, octaves: 2, persistence: 0.4, bitDepth: "32", scaleY: 3 })
const swellLevels = levels(hewnSwells, { outputBlack: 0.7, outputWhite: 0.95 })
const grooveDepth = levels(grainLinesCut, { outputWhite: 0.14 })
const grainGrooves = channelMath(swellLevels, grooveDepth, "subtract")
const splitLip = blend(splitsOn000000ff, splitLips, "lighten")
const splitDepth = levels(splitLip, { outputWhite: 0.6 })
const splitCut2 = channelMath(grainGrooves, splitDepth, "subtract")
const knotDepth = levels(knotsOn000000ff, { outputWhite: 0.08 })
const knotDents = channelMath(splitCut2, knotDepth, "subtract")
const fibre2 = blend(knotDents, fibre, "softLight", { opacity: 0.25 })
const grainKnots = blend(grainLinesCut, knotsOn000000ff, "lighten")
const marksColour = gradientMap(grainKnots, { colors: [{ position: 0, color: "#ffffff" }, { position: 0.4, color: "#b8906c" }, { position: 1, color: "#4e2e1a" }] })
const streakLines = noise("perlin", { scale: 7, fractal: "ridged", tile: true, seed: 410, octaves: 2, persistence: 0.4, bitDepth: "32", scaleY: 1 })
const streakWave = noise("perlin", { scale: 2, tile: true, seed: 411, octaves: 1, scaleY: 3 })
const streaksWaving = warp(streakLines, streakWave, { edges: "wrap" })
const lightStreaks = levels(streaksWaving, { inputBlack: 0.88, inputWhite: 0.97 })
const splitColour = gradientMap(splitsOn000000ff, { colors: [{ position: 0, color: "#ffffff" }, { position: 0.5, color: "#5a3a24" }, { position: 1, color: "#1a0e08" }] })
const splitInk = blend(marksColour, splitColour, "multiply")
const heightSmoothed = blur(fibre2, { radius: 0.6, edges: "wrap" })
const colourFromHeight = gradientMap(heightSmoothed, { colors: [{ position: 0, color: "#160c06" }, { position: 0.3, color: "#2e1c10" }, { position: 0.55, color: "#4a301a" }, { position: 0.75, color: "#5c3e22" }, { position: 0.9, color: "#6a4a2a" }, { position: 1, color: "#765430" }] })
const pieceTone = gradientMap(hewnSwells, { colors: [{ position: 0, color: "#6a6a6a" }, { position: 1, color: "#9a9a9a" }] })
const tonePerPiece = blend(colourFromHeight, pieceTone, "softLight", { opacity: 0.4 })
const drift = noise("perlin", { scale: 2, tile: true, seed: 409, octaves: 3, scaleY: 4 })
const driftHues = gradientMap(drift, { colors: [{ position: 0, color: "#7a4a24" }, { position: 1, color: "#5e4a36" }] })
const hueDrift = blend(tonePerPiece, driftHues, "color", { opacity: 0.3 })
const valueDrift = blend(hueDrift, drift, "softLight", { opacity: 0.18 })
const paintedMarks = blend(valueDrift, splitInk, "multiply", { opacity: 0.8 })
const cavitySoft = blur(heightSmoothed, { radius: 3, edges: "wrap" })
const cavity = levels(cavitySoft, { outputBlack: 0.35 })
const cavityColour = gradientMap(cavity, { colors: [{ position: 0, color: "#2a1206" }, { position: 1, color: "#ffffff" }] })
const paintedCavity = blend(paintedMarks, cavityColour, "multiply", { opacity: 0.3 })
const curvature2 = curvature(heightSmoothed, "convex", { intensity: 1.2, edges: "wrap" })
const edgeMask = levels(curvature2, { inputBlack: 0.05, inputWhite: 0.6 })
const edgeLight = gradientMap(edgeMask, { colors: [{ position: 0, color: "#000000" }, { position: 1, color: "#e0b882" }] })
const wornEdges = blend(paintedCavity, edgeLight, "screen", { opacity: 0.18 })
const saturate = hslAdjust(wornEdges, { saturation: -0.05 })
const normalOpenGL = normalMap(heightSmoothed, { strength: 1.8, flipY: true, smoothRadius: 1, edges: "wrap" })
const streakColour = gradientMap(lightStreaks, { colors: [{ position: 0, color: "#000000" }, { position: 1, color: "#d0a070" }] })
const lightStreaksOn = blend(saturate, streakColour, "screen", { opacity: 0.35 })
export const timber = lightStreaksOn
export const timberNormal = normalOpenGL
