import { tex } from "oj"

const { blend, blur, channelShuffle, curvature, gradientMap, hslAdjust, levels, mask, noise, normalMap, slopeBlur, solidColor, tileGrid, warp } = tex.canvas(256)

const courses = tileGrid({ rows: 7, jointWidth: 0.07, bevel: 0.2, round: 0.35, seed: 21, offsetJitter: 0.6, lengthJitter: 0.5, heightJitter: 0.3, bitDepth: "32" })
const coursesRandom = channelShuffle(courses.random, { outG: "r", outB: "r", outA: "1" })
const outlineNoise = noise("perlin", { tile: true, seed: 601, octaves: 2 })
const raggedOutlines = warp(courses.image, outlineNoise, { strength: 4, edges: "wrap" })
const stoneFace = levels(raggedOutlines, { gamma: 0.8 })
const faceLumps = noise("perlin", { scale: 6, tile: true, seed: 602, octaves: 3, persistence: 0.45, bitDepth: "32" })
const lumpyFaces = blend(stoneFace, faceLumps, "overlay", { opacity: 0.35 })
const chipNoise = noise("perlin", { scale: 12, tile: true, seed: 603, octaves: 3 })
const chipped = slopeBlur(lumpyFaces, chipNoise, "min", { intensity: 3, edges: "wrap" })
const mortarGrit = noise("perlin", { scale: 40, tile: true, seed: 604, octaves: 2 })
const mortarHeight = levels(mortarGrit, { outputBlack: 0.04, outputWhite: 0.14 })
const withMortar = blend(chipped, mortarHeight, "lighten")
const speckNoise = noise("white", { scale: 128, tile: true, seed: 605 })
const specks = levels(speckNoise, { inputBlack: 0.9, inputWhite: 0.98 })
const speckColour = gradientMap(specks, { colors: [{ position: 0, color: "#ffffff" }, { position: 1, color: "#a0988c" }] })
const faceOnly = levels(stoneFace, { inputBlack: 0.05, inputWhite: 0.2 })
const mortarNeutral = solidColor("#808080ff")
const randomOnFacesB = mask(coursesRandom, faceOnly)
const randomOnFaces = blend(mortarNeutral, randomOnFacesB)
const heightSmoothed = blur(withMortar, { radius: 1, edges: "wrap" })
const colourFromHeight = gradientMap(heightSmoothed, { colors: [{ position: 0, color: "#3a3630" }, { position: 0.15, color: "#575148" }, { position: 0.3, color: "#6a655c" }, { position: 0.7, color: "#8a857a" }, { position: 1, color: "#9e988a" }] })
const pieceTone = gradientMap(randomOnFaces, { colors: [{ position: 0, color: "#5c5c5c" }, { position: 0.5, color: "#808080" }, { position: 1, color: "#a8a8a8" }] })
const tonePerPiece = blend(colourFromHeight, pieceTone, "softLight", { opacity: 0.7 })
const pieceHue = gradientMap(randomOnFaces, { colors: [{ position: 0, color: "#8a7a68" }, { position: 0.3, color: "#807a70" }, { position: 0.5, color: "#7c7a76" }, { position: 0.55, color: "#767a80" }, { position: 0.8, color: "#8a7e6c" }, { position: 1, color: "#6e7480" }] })
const huePerPiece = blend(tonePerPiece, pieceHue, "color", { opacity: 0.6 })
const drift = noise("perlin", { scale: 2, tile: true, seed: 606, octaves: 3 })
const driftHues = gradientMap(drift, { colors: [{ position: 0, color: "#8a8070" }, { position: 1, color: "#727a84" }] })
const hueDrift = blend(huePerPiece, driftHues, "color", { opacity: 0.2 })
const valueDrift = blend(hueDrift, drift, "softLight", { opacity: 0.12 })
const paintedMarks = blend(valueDrift, speckColour, "multiply", { opacity: 0.6 })
const cavitySoft = blur(heightSmoothed, { radius: 3, edges: "wrap" })
const cavity = levels(cavitySoft, { outputBlack: 0.25 })
const cavityColour = gradientMap(cavity, { colors: [{ position: 0, color: "#2a2622" }, { position: 1, color: "#ffffff" }] })
const paintedCavity = blend(paintedMarks, cavityColour, "multiply", { opacity: 0.5 })
const curvature2 = curvature(heightSmoothed, "convex", { edges: "wrap" })
const edgeMask = levels(curvature2, { inputBlack: 0.05, inputWhite: 0.6 })
const edgeLight = gradientMap(edgeMask, { colors: [{ position: 0, color: "#000000" }, { position: 1, color: "#f4ece0" }] })
const wornEdges = blend(paintedCavity, edgeLight, "screen", { opacity: 0.22 })
const saturate = hslAdjust(wornEdges)
const normalOpenGL = normalMap(heightSmoothed, { strength: 2.2, flipY: true, smoothRadius: 1, edges: "wrap" })
export const stone = saturate
export const stoneNormal = normalOpenGL
