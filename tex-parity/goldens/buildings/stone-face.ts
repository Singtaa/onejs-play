import { tex } from "oj"

const { blend, blur, channelMath, curvature, gradientMap, hslAdjust, levels, mask, noise, normalMap, warp } = tex.canvas(128)

const hewnLumps = noise("perlin", { scale: 2, tile: true, seed: 621, bitDepth: "32" })
const chiselA = noise("perlin", { scale: 3, fractal: "ridged", tile: true, seed: 622, octaves: 1, bitDepth: "32", scaleY: 22 })
const chiselB = noise("perlin", { scale: 22, fractal: "ridged", tile: true, seed: 623, octaves: 1, bitDepth: "32", scaleY: 3 })
const patchNoise = noise("perlin", { scale: 3, tile: true, seed: 624, octaves: 2 })
const chiselPatches = levels(patchNoise, { inputBlack: 0.48, inputWhite: 0.52 })
const chiselStrokesB = mask(chiselB, chiselPatches)
const chiselStrokes = blend(chiselA, chiselStrokesB)
const slantNoise = noise("perlin", { scale: 2, tile: true, seed: 625, octaves: 1 })
const chiselSlant = warp(chiselStrokes, slantNoise, { strength: 0.8, edges: "wrap" })
const dashNoise = noise("perlin", { scale: 14, tile: true, seed: 626, octaves: 2 })
const dashes = levels(dashNoise, { inputBlack: 0.5, inputWhite: 0.6 })
const chiselCut = levels(chiselSlant, { inputBlack: 0.72, inputWhite: 0.92 })
const chiselMarks = blend(chiselCut, dashes, "multiply")
const pitNoise = noise("perlin", { scale: 18, tile: true, seed: 627, octaves: 1, bitDepth: "32" })
const pits = levels(pitNoise, { inputBlack: 0.74, inputWhite: 0.8 })
const faceBody = levels(hewnLumps, { outputBlack: 0.3, outputWhite: 0.9 })
const chiselSoft = blur(chiselMarks, { radius: 0.7, edges: "wrap" })
const chiselDepth = levels(chiselSoft, { outputWhite: 0.1 })
const chiselled = channelMath(faceBody, chiselDepth, "subtract")
const pitSoft = blur(pits, { radius: 0.8, edges: "wrap" })
const pitDepth = levels(pitSoft, { outputWhite: 0.25 })
const pitted = channelMath(chiselled, pitDepth, "subtract")
const grain = noise("perlin", { scale: 12, tile: true, seed: 628, octaves: 2 })
const grainy = blend(pitted, grain, "softLight", { opacity: 0.25 })
const warmCool = noise("perlin", { scale: 2, tile: true, seed: 629, octaves: 2 })
const speckNoise = noise("perlin", { scale: 30, tile: true, seed: 630, octaves: 1, bitDepth: "32" })
const specks = levels(speckNoise, { inputBlack: 0.72, inputWhite: 0.8 })
const speckColour = gradientMap(specks, { colors: [{ position: 0, color: "#ffffff" }, { position: 1, color: "#a8a096" }] })
const heightSmoothed = blur(grainy, { radius: 0.8, edges: "wrap" })
const colourFromHeight = gradientMap(heightSmoothed, { colors: [{ position: 0, color: "#2e2b26" }, { position: 0.3, color: "#4e4a42" }, { position: 0.5, color: "#686359" }, { position: 0.75, color: "#888378" }, { position: 1, color: "#a29c90" }] })
const pieceTone = gradientMap(warmCool, { colors: [{ position: 0, color: "#585858" }, { position: 1, color: "#a8a8a8" }] })
const tonePerPiece = blend(colourFromHeight, pieceTone, "softLight", { opacity: 0.7 })
const drift = noise("perlin", { scale: 2, tile: true, seed: 631, octaves: 3 })
const driftHues = gradientMap(drift, { colors: [{ position: 0, color: "#8e7c66" }, { position: 1, color: "#6a7888" }] })
const hueDrift = blend(tonePerPiece, driftHues, "color", { opacity: 0.55 })
const valueDrift = blend(hueDrift, drift, "softLight", { opacity: 0.33 })
const paintedMarks = blend(valueDrift, speckColour, "multiply", { opacity: 0.5 })
const cavitySoft = blur(heightSmoothed, { radius: 2, edges: "wrap" })
const cavity = levels(cavitySoft, { outputBlack: 0.3 })
const cavityColour = gradientMap(cavity, { colors: [{ position: 0, color: "#2a2622" }, { position: 1, color: "#ffffff" }] })
const paintedCavity = blend(paintedMarks, cavityColour, "multiply", { opacity: 0.45 })
const curvature2 = curvature(heightSmoothed, "convex", { intensity: 0.8, edges: "wrap" })
const edgeMask = levels(curvature2, { inputBlack: 0.05, inputWhite: 0.6 })
const edgeLight = gradientMap(edgeMask, { colors: [{ position: 0, color: "#000000" }, { position: 1, color: "#f4ece0" }] })
const wornEdges = blend(paintedCavity, edgeLight, "screen", { opacity: 0.15 })
const saturate = hslAdjust(wornEdges)
const normalOpenGL = normalMap(heightSmoothed, { strength: 1.8, flipY: true, smoothRadius: 1, edges: "wrap" })
const lichenGathers = noise("perlin", { scale: 2, tile: true, seed: 634, octaves: 2, bitDepth: "32" })
const lichenPatches = levels(lichenGathers, { inputBlack: 0.4, inputWhite: 0.65 })
const lichenNoise = noise("perlin", { scale: 7, tile: true, seed: 632, persistence: 0.6, bitDepth: "32" })
const lichenLow = blend(lichenNoise, lichenPatches, "multiply")
const lichenWhere = levels(lichenLow, { inputBlack: 0.42, inputWhite: 0.47 })
const lichenTint = noise("perlin", { scale: 12, tile: true, seed: 633, octaves: 2 })
const lichenColour = gradientMap(lichenTint, { colors: [{ position: 0, color: "#7c8060ff" }, { position: 0.6, color: "#94946eff" }, { position: 1, color: "#aaa688ff" }] })
const lichenOnStone = blend(lichenColour, saturate, "softLight", { opacity: 0.5 })
const lichenB = mask(lichenOnStone, lichenWhere)
const lichen = blend(saturate, lichenB)
export const stoneFace = lichen
export const stoneFaceNormal = normalOpenGL
