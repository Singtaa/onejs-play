import { tex } from "oj"

const { blend, blur, curvature, directionalWarp, gradient, gradientMap, hslAdjust, invert, levels, mask, noise, normalMap, solidColor, tile, warp } = tex.canvas(256)

const y = gradient({ angle: 90 })
const layerRamp = tile(y, { repeatX: 1, repeatY: 6 })
const clumps = noise("perlin", { scale: 12, tile: true, seed: 801, octaves: 2, scaleY: 6 })
const strawEnds = noise("perlin", { scale: 48, fractal: "ridged", tile: true, seed: 802, octaves: 1, scaleY: 6 })
const clumpedEnds = blend(clumps, strawEnds, "overlay", { opacity: 0.6 })
const raggedLayers = directionalWarp(layerRamp, clumpedEnds, { angle: 90, intensity: 18, edges: "wrap" })
const layerSwell = levels(raggedLayers, { gamma: 0.7, outputBlack: 0.15 })
const strands = noise("perlin", { scale: 70, fractal: "ridged", tile: true, seed: 803, octaves: 2, bitDepth: "32", scaleY: 3 })
const bundles = noise("perlin", { scale: 16, tile: true, seed: 804, octaves: 2, scaleY: 2 })
const strandsInBundles = blend(strands, bundles, "overlay", { opacity: 0.5 })
const strandWave = noise("perlin", { scale: 4, tile: true, seed: 805, octaves: 2 })
const strandsWaving = warp(strandsInBundles, strandWave, { strength: 6, edges: "wrap" })
const bulge = levels(bundles, { outputBlack: 0.7 })
const bundleBulge = blend(layerSwell, bulge, "multiply")
const strawOnLayers = blend(bundleBulge, strandsWaving, "overlay", { opacity: 0.45 })
const strawSoft = blur(strawOnLayers, { radius: 0.5, edges: "wrap" })
const strandGaps = levels(strandsWaving, { inputWhite: 0.35 })
const strandInk = gradientMap(strandGaps, { colors: [{ position: 0, color: "#7a5a2a" }, { position: 1, color: "#ffffff" }] })
const heightSmoothed = blur(strawSoft, { radius: 0.6, edges: "wrap" })
const colourFromHeight = gradientMap(heightSmoothed, { colors: [{ position: 0, color: "#3a2a10" }, { position: 0.25, color: "#6a4e20" }, { position: 0.5, color: "#9a7a34" }, { position: 0.75, color: "#b8963e" }, { position: 1, color: "#d0b05a" }] })
const pieceTone = gradientMap(bundles, { colors: [{ position: 0, color: "#6a6a6a" }, { position: 1, color: "#9a9a9a" }] })
const tonePerPiece = blend(colourFromHeight, pieceTone, "softLight", { opacity: 0.5 })
const drift = noise("perlin", { scale: 2, tile: true, seed: 806, octaves: 3 })
const driftHues = gradientMap(drift, { colors: [{ position: 0, color: "#b08a3a" }, { position: 1, color: "#8a7a4a" }] })
const hueDrift = blend(tonePerPiece, driftHues, "color", { opacity: 0.3 })
const valueDrift = blend(hueDrift, drift, "softLight", { opacity: 0.18 })
const paintedMarks = blend(valueDrift, strandInk, "multiply", { opacity: 0.5 })
const cavitySoft = blur(heightSmoothed, { radius: 3, edges: "wrap" })
const cavity = levels(cavitySoft, { outputBlack: 0.2 })
const cavityColour = gradientMap(cavity, { colors: [{ position: 0, color: "#3a2408" }, { position: 1, color: "#ffffff" }] })
const paintedCavity = blend(paintedMarks, cavityColour, "multiply", { opacity: 0.45 })
const curvature2 = curvature(heightSmoothed, "convex", { edges: "wrap" })
const edgeMask = levels(curvature2, { inputBlack: 0.05, inputWhite: 0.6 })
const edgeLight = gradientMap(edgeMask, { colors: [{ position: 0, color: "#000000" }, { position: 1, color: "#fff0c0" }] })
const wornEdges = blend(paintedCavity, edgeLight, "screen", { opacity: 0.2 })
const saturate = hslAdjust(wornEdges)
const normalOpenGL = normalMap(heightSmoothed, { strength: 1.6, flipY: true, smoothRadius: 1, edges: "wrap" })
const lipBand = levels(raggedLayers, { inputWhite: 0.22 })
const underTheLip = invert(lipBand)
const lipShadowColour = gradientMap(underTheLip, { colors: [{ position: 0, color: "#ffffff" }, { position: 1, color: "#3a2810" }] })
const lipShadow = blend(saturate, lipShadowColour, "multiply", { opacity: 0.7 })
const streakNoise = noise("perlin", { scale: 7, tile: true, seed: 807, octaves: 2, bitDepth: "32", scaleY: 0.8 })
const streaks = levels(streakNoise, { inputBlack: 0.58, inputWhite: 0.72 })
const weathered = solidColor("#8c8676ff")
const weatheredGrey = blend(lipShadow, weathered, "color", { opacity: 0.85 })
const streakMax = solidColor("#ffffffff")
const streakOpacity = levels(streakMax, { outputWhite: 0.7 })
const streakFade = blend(streaks, streakOpacity, "multiply")
const greyStreaksB = mask(weatheredGrey, streakFade)
const greyStreaks = blend(lipShadow, greyStreaksB)
const lessSaturated = hslAdjust(greyStreaks, { saturation: -0.12 })
export const thatch = lessSaturated
export const thatchNormal = normalOpenGL
