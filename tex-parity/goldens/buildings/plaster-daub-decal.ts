import { tex } from "oj"

const { alpha, blend, blur, channelMath, curvature, gradient, gradientMap, hslAdjust, levels, mask, noise, normalMap, slopeBlur, solidColor } = tex.canvas(256)

const patchFalloff = gradient("radial", { colors: [{ position: 0, color: "#ffffff" }, { position: 1, color: "#000000" }] })
const patchShape = noise("perlin", { scale: 4, seed: 521, persistence: 0.55, bitDepth: "32" })
const patchField = blend(patchFalloff, patchShape, "overlay", { opacity: 0.9 })
const broken = levels(patchField, { inputBlack: 0.6, inputWhite: 0.63 })
const lipSpread = blur(broken, { edges: "wrap" })
const washLip = levels(lipSpread, { inputBlack: 0.02, inputWhite: 0.1 })
const daubLumps = noise("perlin", { scale: 6, seed: 522, octaves: 3, bitDepth: "32" })
const washLevel = levels(washLip, { outputBlack: 0.3, outputWhite: 0.9 })
const sink = levels(broken, { outputWhite: 0.45 })
const daubSunk = channelMath(washLevel, sink, "subtract")
const lumpGain = levels(daubLumps, { outputBlack: 0.35, outputWhite: 0.65 })
const daubLumpy = blend(daubSunk, lumpGain, "overlay", { opacity: 0.5 })
const chipNoise = noise("perlin", { scale: 14, seed: 523, octaves: 3 })
const chippedLip = slopeBlur(daubLumpy, chipNoise, "min", { intensity: 2.5, edges: "wrap" })
const straw = noise("perlin", { scale: 30, fractal: "ridged", seed: 524, octaves: 2, scaleY: 8 })
const daubStraw = gradientMap(straw, { colors: [{ position: 0, color: "#6a4c30ff" }, { position: 0.7, color: "#8a6640ff" }, { position: 1, color: "#b08a52ff" }] })
const heightSmoothed = blur(chippedLip, { radius: 0.6, edges: "wrap" })
const colourFromHeight = gradientMap(heightSmoothed, { colors: [{ position: 0, color: "#3e2c1c" }, { position: 0.15, color: "#5a4028" }, { position: 0.4, color: "#7a5a38" }, { position: 0.6, color: "#b4a282" }, { position: 0.8, color: "#c8b896" }, { position: 1, color: "#d6c8a6" }] })
const drift = noise("perlin", { scale: 2, tile: true, seed: 525, octaves: 3 })
const driftHues = gradientMap(drift, { colors: [{ position: 0, color: "#d0b888" }, { position: 1, color: "#c8c4b4" }] })
const hueDrift = blend(colourFromHeight, driftHues, "color", { opacity: 0.25 })
const valueDrift = blend(hueDrift, drift, "softLight", { opacity: 0.15 })
const cavitySoft = blur(heightSmoothed, { radius: 2, edges: "wrap" })
const cavity = levels(cavitySoft, { outputBlack: 0.35 })
const cavityColour = gradientMap(cavity, { colors: [{ position: 0, color: "#4a3420" }, { position: 1, color: "#ffffff" }] })
const paintedCavity = blend(valueDrift, cavityColour, "multiply", { opacity: 0.45 })
const curvature2 = curvature(heightSmoothed, "convex", { intensity: 1.2, edges: "wrap" })
const edgeMask = levels(curvature2, { inputBlack: 0.05, inputWhite: 0.6 })
const edgeLight = gradientMap(edgeMask, { colors: [{ position: 0, color: "#000000" }, { position: 1, color: "#fff8e8" }] })
const wornEdges = blend(paintedCavity, edgeLight, "screen", { opacity: 0.25 })
const saturate = hslAdjust(wornEdges)
const normalOpenGL = normalMap(heightSmoothed, { strength: 1.4, flipY: true, smoothRadius: 1, edges: "wrap" })
const noStraw = solidColor("#ffffffff")
const strawInsideB = mask(daubStraw, broken)
const strawInside = blend(noStraw, strawInsideB)
const strawInDaub = blend(saturate, strawInside, "multiply", { opacity: 0.6 })
const alphaSpread = blur(washLip, { radius: 1.5, edges: "wrap" })
const decalAlpha = levels(alphaSpread, { inputBlack: 0.05, inputWhite: 0.3 })
export const plasterDaubDecal = alpha(strawInDaub, decalAlpha)
export const plasterDaubDecalNormal = normalOpenGL
