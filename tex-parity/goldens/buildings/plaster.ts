import { tex } from "oj"

const { blend, blur, channelMath, curvature, gradientMap, hslAdjust, invert, levels, mask, noise, normalMap, warp } = tex.canvas(256)

const lumps = noise("perlin", { scale: 3, tile: true, seed: 501, bitDepth: "32" })
const sweepStrokes = noise("perlin", { scale: 6, tile: true, seed: 502, octaves: 2, persistence: 0.4, bitDepth: "32", scaleY: 18 })
const sweepSwirl = noise("perlin", { scale: 2, tile: true, seed: 503, octaves: 2 })
const sweepsSwirled = warp(sweepStrokes, sweepSwirl, { strength: 40, edges: "wrap" })
const flakeNoise = noise("perlin", { scale: 10, tile: true, seed: 504, octaves: 3, persistence: 0.6, bitDepth: "32" })
const flaked = levels(flakeNoise, { inputBlack: 0.64, inputWhite: 0.67 })
const crackCells = noise("voronoi", { scale: 4, voronoiMode: "f2-f1", tile: true, seed: 505, octaves: 1, bitDepth: "32" })
const crackThin = levels(crackCells, { inputWhite: 0.025 })
const crackLine = invert(crackThin)
const crackWhereNoise = noise("perlin", { scale: 3, tile: true, seed: 506, octaves: 2 })
const crackWhere = levels(crackWhereNoise, { inputBlack: 0.56, inputWhite: 0.64 })
const cracks = blend(crackLine, crackWhere, "multiply")
const crackWobble = noise("perlin", { tile: true, seed: 507, octaves: 2, scaleY: 8 })
const cracksWobble = warp(cracks, crackWobble, { strength: 5, edges: "wrap" })
const lumpsSweeps = blend(lumps, sweepsSwirled, "overlay", { opacity: 0.7 })
const washBody = levels(lumpsSweeps, { outputBlack: 0.3, outputWhite: 0.92 })
const flakeDepth = levels(flaked, { outputWhite: 0.3 })
const flakeStep = channelMath(washBody, flakeDepth, "subtract")
const crackDepth = levels(cracksWobble, { outputWhite: 0.2 })
const crackCut = channelMath(flakeStep, crackDepth, "subtract")
const blotches = noise("perlin", { scale: 3, tile: true, seed: 508, octaves: 3, persistence: 0.55 })
const daubStraw = noise("perlin", { scale: 30, tile: true, seed: 509, octaves: 2 })
const daubColour = gradientMap(daubStraw, { colors: [{ position: 0, color: "#6e5034ff" }, { position: 1, color: "#9a7448ff" }] })
const crackInk = gradientMap(cracksWobble, { colors: [{ position: 0, color: "#ffffff" }, { position: 0.5, color: "#b09a80" }, { position: 1, color: "#6a5640" }] })
const heightSmoothed = blur(crackCut, { radius: 0.6, edges: "wrap" })
const colourFromHeight = gradientMap(heightSmoothed, { colors: [{ position: 0, color: "#5a4a36" }, { position: 0.3, color: "#8e7c60" }, { position: 0.55, color: "#b4a282" }, { position: 0.8, color: "#c8b896" }, { position: 1, color: "#d6c8a6" }] })
const pieceTone = gradientMap(blotches, { colors: [{ position: 0, color: "#505050" }, { position: 0.5, color: "#808080" }, { position: 1, color: "#a8a8a8" }] })
const tonePerPiece = blend(colourFromHeight, pieceTone, "softLight", { opacity: 0.55 })
const drift = noise("perlin", { scale: 2, tile: true, seed: 510, octaves: 3 })
const driftHues = gradientMap(drift, { colors: [{ position: 0, color: "#d0b888" }, { position: 1, color: "#c8c4b4" }] })
const hueDrift = blend(tonePerPiece, driftHues, "color", { opacity: 0.35 })
const valueDrift = blend(hueDrift, drift, "softLight", { opacity: 0.21 })
const paintedMarks = blend(valueDrift, crackInk, "multiply", { opacity: 0.55 })
const cavitySoft = blur(heightSmoothed, { radius: 2, edges: "wrap" })
const cavity = levels(cavitySoft, { outputBlack: 0.5 })
const cavityColour = gradientMap(cavity, { colors: [{ position: 0, color: "#5a4630" }, { position: 1, color: "#ffffff" }] })
const paintedCavity = blend(paintedMarks, cavityColour, "multiply", { opacity: 0.3 })
const curvature2 = curvature(heightSmoothed, "convex", { edges: "wrap" })
const edgeMask = levels(curvature2, { inputBlack: 0.05, inputWhite: 0.6 })
const edgeLight = gradientMap(edgeMask, { colors: [{ position: 0, color: "#000000" }, { position: 1, color: "#fff8e8" }] })
const wornEdges = blend(paintedCavity, edgeLight, "screen", { opacity: 0.15 })
const saturate = hslAdjust(wornEdges)
const normalOpenGL = normalMap(heightSmoothed, { strength: 1.2, flipY: true, smoothRadius: 1, edges: "wrap" })
const flakeEdge = blur(flaked, { radius: 0.6, edges: "wrap" })
const flakedToDaubB = mask(daubColour, flakeEdge)
const flakedToDaub = blend(saturate, flakedToDaubB)
export const plaster = flakedToDaub
export const plasterNormal = normalOpenGL
