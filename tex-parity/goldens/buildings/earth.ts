import { tex } from "oj"

const { alphaMerge, blend, blur, channelMath, curvature, gradient, gradientMap, hslAdjust, invert, levels, noise, normalMap, scatter, solidColor, warp } = tex.canvas(256)

const soil = noise("perlin", { scale: 3, tile: true, seed: 901, octaves: 5, bitDepth: "32" })
const crumbs = noise("perlin", { scale: 24, tile: true, seed: 902, octaves: 3 })
const soilCrumbs = blend(soil, crumbs, "softLight", { opacity: 0.3 })
const soilHeight = levels(soilCrumbs, { outputBlack: 0.3, outputWhite: 0.55 })
const pebbleDome = gradient("radial", { colors: [{ position: 0, color: "#ffffff" }, { position: 1, color: "#000000" }], width: 24, height: 24 })
const pebbleNoise = noise("perlin", { scale: 3, seed: 903, octaves: 2, width: 24, height: 24 })
const pebbleShape = warp(pebbleDome, pebbleNoise, { strength: 4, edges: "clamp" })
const pebbleProfile = levels(pebbleShape, { inputBlack: 0.2, inputWhite: 0.6 })
const pebbleCut = levels(pebbleShape, { inputBlack: 0.2, inputWhite: 0.3 })
const pebbleStamp = alphaMerge(pebbleProfile, pebbleCut)
const pebbles = scatter(pebbleStamp, { count: 40, seed: 904, scaleMin: 0.4, rotationRange: 180, opacityMin: 1, edges: "wrap" })
const pebblesUnder = solidColor("#000000ff")
const pebblesOn000000ff = blend(pebblesUnder, pebbles.image)
const pebbleHeight = levels(pebblesOn000000ff, { outputWhite: 0.64 })
const pebblesSunk = blend(soilHeight, pebbleHeight, "lighten")
const crackCells = noise("voronoi", { scale: 7, voronoiMode: "f2-f1", tile: true, seed: 905, octaves: 1, bitDepth: "32" })
const crackThin = levels(crackCells, { inputWhite: 0.04 })
const crackLines = invert(crackThin)
const crackWhereNoise = noise("perlin", { scale: 2, tile: true, seed: 906, octaves: 2 })
const crackWhere = levels(crackWhereNoise, { inputBlack: 0.55, inputWhite: 0.7 })
const cracks = blend(crackLines, crackWhere, "multiply")
const crackDepth = levels(cracks, { outputWhite: 0.15 })
const crackCut = channelMath(pebblesSunk, crackDepth, "subtract")
const packedNoise = noise("perlin", { scale: 3, tile: true, seed: 907, octaves: 3 })
const packedPatches = levels(packedNoise, { inputBlack: 0.4, inputWhite: 0.62 })
const crackInk = gradientMap(cracks, { colors: [{ position: 0, color: "#ffffff" }, { position: 1, color: "#5a4030" }] })
const heightSmoothed = blur(crackCut, { radius: 0.7, edges: "wrap" })
const colourFromHeight = gradientMap(heightSmoothed, { colors: [{ position: 0, color: "#2e221a" }, { position: 0.3, color: "#5a4434" }, { position: 0.45, color: "#6e5644" }, { position: 0.58, color: "#7c6450" }, { position: 0.64, color: "#6a6258" }, { position: 1, color: "#8a8276" }] })
const pieceTone = gradientMap(packedPatches, { colors: [{ position: 0, color: "#5a5a5a" }, { position: 0.5, color: "#808080" }, { position: 1, color: "#b8b8b8" }] })
const tonePerPiece = blend(colourFromHeight, pieceTone, "softLight")
const drift = noise("perlin", { scale: 1.5, tile: true, seed: 908, octaves: 3 })
const driftHues = gradientMap(drift, { colors: [{ position: 0, color: "#7a5a40" }, { position: 1, color: "#6a6258" }] })
const hueDrift = blend(tonePerPiece, driftHues, "color", { opacity: 0.35 })
const valueDrift = blend(hueDrift, drift, "softLight", { opacity: 0.21 })
const paintedMarks = blend(valueDrift, crackInk, "multiply", { opacity: 0.6 })
const cavitySoft = blur(heightSmoothed, { radius: 3, edges: "wrap" })
const cavity = levels(cavitySoft, { outputBlack: 0.3 })
const cavityColour = gradientMap(cavity, { colors: [{ position: 0, color: "#24182a" }, { position: 1, color: "#ffffff" }] })
const paintedCavity = blend(paintedMarks, cavityColour, "multiply", { opacity: 0.5 })
const curvature2 = curvature(heightSmoothed, "convex", { intensity: 1.5, edges: "wrap" })
const edgeMask = levels(curvature2, { inputBlack: 0.05, inputWhite: 0.6 })
const edgeLight = gradientMap(edgeMask, { colors: [{ position: 0, color: "#000000" }, { position: 1, color: "#f0e0c8" }] })
const wornEdges = blend(paintedCavity, edgeLight, "screen", { opacity: 0.12 })
const saturate = hslAdjust(wornEdges, { saturation: -0.05 })
const normalOpenGL = normalMap(heightSmoothed, { strength: 1.2, flipY: true, smoothRadius: 1, edges: "wrap" })
export const earth = saturate
export const earthNormal = normalOpenGL
