import { tex } from "oj"

const { alphaMerge, blend, blur, channelMath, channelShuffle, curvature, directionalWarp, gradient, gradientMap, hslAdjust, invert, levels, noise, normalMap, scatter, slopeBlur, solidColor, tileGrid, warp } = tex.canvas(256)

const boards = tileGrid({ columns: 1, rows: 4, jointWidth: 0.07, bevel: 0.16, round: 0.04, seed: 12, offsetJitter: 0.15, heightJitter: 0.25, bitDepth: "32" })
const boardsRandom = channelShuffle(boards.random, { outG: "r", outB: "r", outA: "1" })
const boardsU = channelShuffle(boards.uv, { outG: "r", outB: "r", outA: "1" })
const boardsV = channelShuffle(boards.uv, { outR: "g", outB: "g", outA: "1" })
const boardFace = levels(boards.image, { gamma: 1.3 })
const grainLines = noise("perlin", { scale: 1, fractal: "ridged", tile: true, seed: 301, octaves: 2, persistence: 0.4, bitDepth: "32", scaleY: 10 })
const grainWave = noise("perlin", { scale: 2, tile: true, seed: 302, octaves: 2 })
const grainWaving = warp(grainLines, grainWave, { strength: 8, edges: "wrap" })
const grainPerBoard = directionalWarp(grainWaving, boardsRandom, { angle: 90, intensity: 140, edges: "wrap" })
const grainLinesCut = levels(grainPerBoard, { inputBlack: 0.8, inputWhite: 0.93 })
const fibre = noise("perlin", { scale: 3, tile: true, seed: 303, octaves: 2, scaleY: 40 })
const knotDome = gradient("radial", { colors: [{ position: 0, color: "#ffffff" }, { position: 1, color: "#000000" }], width: 40, height: 22 })
const knotNoise = noise("perlin", { scale: 3, seed: 305, octaves: 2, width: 40, height: 22, scaleY: 1.6500000000000001 })
const knotUneven = warp(knotDome, knotNoise, { strength: 3, edges: "clamp" })
const knotRingAtMark = solidColor("#595959ff")
const knotRingAt = blend(knotUneven, knotRingAtMark, "difference")
const knotRingBand = levels(knotRingAt, { inputWhite: 0.12 })
const knotRingMark = invert(knotRingBand)
const knotCoreMark = levels(knotUneven, { inputBlack: 0.6, inputWhite: 0.8 })
const knotMark = blend(knotRingMark, knotCoreMark, "lighten")
const knotCut = levels(knotUneven, { inputBlack: 0.05, inputWhite: 0.15 })
const knotStamp = alphaMerge(knotMark, knotCut)
const knots = scatter(knotStamp, { count: 3, seed: 306, scaleMin: 0.8, scaleMax: 1.2, rotationRange: 6, opacityMin: 1, edges: "wrap" })
const knotsUnder = solidColor("#000000ff")
const knotsOn000000ff = blend(knotsUnder, knots.image)
const grooveDepth = levels(grainLinesCut, { outputWhite: 0.12 })
const grainGrooves = channelMath(boardFace, grooveDepth, "subtract")
const knotDepth = levels(knotsOn000000ff, { outputWhite: 0.1 })
const knotDents = channelMath(grainGrooves, knotDepth, "subtract")
const fibre2 = blend(knotDents, fibre, "softLight", { opacity: 0.2 })
const chipNoise = noise("perlin", { scale: 6, tile: true, seed: 304, octaves: 3 })
const chipped = slopeBlur(fibre2, chipNoise, "min", { intensity: 2.5, edges: "wrap" })
const boardEnds1U = invert(boardsU)
const boardEnds2u1 = blend(boardsU, boardEnds1U, "difference")
const boardEnds = invert(boardEnds2u1)
const nailXOffMark = solidColor("#0d0d0dff")
const nailXOff = blend(boardEnds, nailXOffMark, "difference")
const nailXNear = levels(nailXOff, { inputWhite: 0.022 })
const nailX = invert(nailXNear)
const boardMiddle1U = invert(boardsV)
const boardMiddle2u1 = blend(boardsV, boardMiddle1U, "difference")
const boardMiddle = invert(boardMiddle2u1)
const nailYOffMark = solidColor("#808080ff")
const nailYOff = blend(boardMiddle, nailYOffMark, "difference")
const nailYNear = levels(nailYOff, { inputWhite: 0.09 })
const nailY = invert(nailYNear)
const nail = blend(nailX, nailY, "multiply")
const nailHead = levels(nail, { inputBlack: 0.2, inputWhite: 0.55 })
const nailLift = levels(nailHead, { outputWhite: 0.15 })
const withNails = blend(chipped, nailLift, "add")
const buttDistance1U = invert(boardsU)
const buttDistance2u1 = blend(boardsU, buttDistance1U, "difference")
const buttDistance = invert(buttDistance2u1)
const buttNear = levels(buttDistance, { inputWhite: 0.02 })
const nearAButt = invert(buttNear)
const buttZone = levels(nearAButt, { outputWhite: 0.3 })
const buttsLifted = blend(withNails, buttZone, "lighten")
const grainKnots = blend(grainLinesCut, knotsOn000000ff, "lighten")
const marksColour = gradientMap(grainKnots, { colors: [{ position: 0, color: "#ffffff" }, { position: 0.4, color: "#c09c7c" }, { position: 1, color: "#6a4228" }] })
const heightSmoothed = blur(buttsLifted, { radius: 0.6, edges: "wrap" })
const colourFromHeight = gradientMap(heightSmoothed, { colors: [{ position: 0, color: "#3e2a1c" }, { position: 0.1, color: "#4e3424" }, { position: 0.3, color: "#7a5634" }, { position: 0.55, color: "#94683e" }, { position: 0.8, color: "#a8784a" }, { position: 1, color: "#b88a54" }] })
const pieceTone = gradientMap(boardsRandom, { colors: [{ position: 0, color: "#5a5a5a" }, { position: 1, color: "#a8a8a8" }] })
const tonePerPiece = blend(colourFromHeight, pieceTone, "softLight", { opacity: 0.5 })
const pieceHue = gradientMap(boardsRandom, { colors: [{ position: 0, color: "#7a3e20" }, { position: 0.5, color: "#80502c" }, { position: 1, color: "#8a6038" }] })
const huePerPiece = blend(tonePerPiece, pieceHue, "color", { opacity: 0.3 })
const drift = noise("perlin", { scale: 2, tile: true, seed: 307, octaves: 3 })
const driftHues = gradientMap(drift, { colors: [{ position: 0, color: "#8a6234" }, { position: 1, color: "#6e5a40" }] })
const hueDrift = blend(huePerPiece, driftHues, "color", { opacity: 0.25 })
const valueDrift = blend(hueDrift, drift, "softLight", { opacity: 0.15 })
const paintedMarks = blend(valueDrift, marksColour, "multiply", { opacity: 0.75 })
const cavitySoft = blur(heightSmoothed, { radius: 3, edges: "wrap" })
const cavity = levels(cavitySoft, { outputBlack: 0.3 })
const cavityColour = gradientMap(cavity, { colors: [{ position: 0, color: "#3a1a0a" }, { position: 1, color: "#ffffff" }] })
const paintedCavity = blend(paintedMarks, cavityColour, "multiply", { opacity: 0.35 })
const curvature2 = curvature(heightSmoothed, "convex", { intensity: 1.2, edges: "wrap" })
const edgeMask = levels(curvature2, { inputBlack: 0.05, inputWhite: 0.6 })
const edgeLight = gradientMap(edgeMask, { colors: [{ position: 0, color: "#000000" }, { position: 1, color: "#f0d0a0" }] })
const wornEdges = blend(paintedCavity, edgeLight, "screen", { opacity: 0.22 })
const saturate = hslAdjust(wornEdges, { saturation: -0.12 })
const normalOpenGL = normalMap(heightSmoothed, { strength: 1.6, flipY: true, smoothRadius: 1, edges: "wrap" })
const iron = gradientMap(nailHead, { colors: [{ position: 0, color: "#ffffffff" }, { position: 0.05, color: "#6a6058ff" }, { position: 0.6, color: "#3a3430ff" }, { position: 1, color: "#5a524cff" }] })
const nailIron = blend(saturate, iron, "multiply")
export const planks = nailIron
export const planksNormal = normalOpenGL
