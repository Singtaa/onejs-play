#!/usr/bin/env node
/**
 * Writes oj's copy of xatlas, the lightmap unwrapper, from the pinned npm package.
 *
 *     node scripts/vendor-xatlas.mjs
 *
 * The same arrangement as vendor-recast.mjs: the glue is vendored as one ES
 * module that never loads its own .wasm (src/wasm.ts hands it the module
 * through Emscripten's instantiateWasm hook), and the module ships as
 * assets/@ojplay/wasm/xatlas-<version>.wasm.
 *
 * xatlas-wasm carries its module inside the glue, as a string literal, and
 * reaches for Node's `module` when it runs under Node. So the module is
 * decoded out of that literal into the .wasm, the literal is replaced by a
 * refusal, Node is never detected, and the factory is opened to take the
 * hook. Each edit is checked to match exactly once, so a new release that
 * moves any of them stops this script rather than vendoring half a patch.
 *
 * Writes src/light/xatlas.vendor.js, src/light/xatlas.version.ts and the .wasm.
 * unwrap.test.ts fails when they and the installed package disagree.
 */

import * as esbuild from "esbuild"
import { createHash } from "node:crypto"
import fs from "node:fs"
import path from "node:path"
import vm from "node:vm"

const ROOT = path.resolve(import.meta.dirname, "..")
const pkgDir = path.join(ROOT, "node_modules/xatlas-wasm")
const version = JSON.parse(fs.readFileSync(path.join(pkgDir, "package.json"), "utf8")).version
let source = fs.readFileSync(path.join(pkgDir, "dist/index.mjs"), "utf8")

/** Replaces `from`, which must occur exactly once, with `to`. */
function replaceOnce(from, to, what) {
    const count = source.split(from).length - 1
    if (count !== 1) throw new Error(`xatlas-wasm@${version}: expected ${what} once, found it ${count} times`)
    source = source.replace(from, () => to)
}

// The module, from the literal findWasmBinary decodes: each char is a byte, as the glue's binaryDecode reads it.
const literal = /return binaryDecode\(('(?:[^'\\]|\\.)*')\);/s.exec(source)
if (literal === null) throw new Error(`xatlas-wasm@${version}: no inline module in findWasmBinary`)
const chars = vm.runInNewContext(literal[1])
const wasmBytes = Buffer.alloc(chars.length)
for (let i = 0; i < chars.length; i++) {
    const c = chars.charCodeAt(i)
    wasmBytes[i] = ~c >> 8 & c
}
const imports = WebAssembly.Module.imports(new WebAssembly.Module(wasmBytes))
const sha256 = createHash("sha256").update(wasmBytes).digest("hex")

replaceOnce(literal[0], `throw new Error("[oj] xatlas is handed its module by src/wasm.ts and never loads its own");`, "the inline module")
replaceOnce(
    `var ENVIRONMENT_IS_NODE = globalThis.process?.versions?.node && globalThis.process?.type != "renderer";`,
    `var ENVIRONMENT_IS_NODE = false;`,
    "the Node detection",
)
replaceOnce(
    `  if (ENVIRONMENT_IS_NODE) {\n    const { createRequire } = await import("node:module");\n    var require2 = createRequire(import.meta.url);\n  }\n`,
    "",
    "the Node require",
)
replaceOnce(`async function createXAtlas() {\n  const module = await xatlas_default();`, `async function createXAtlas(moduleArg) {\n  const module = await xatlas_default(moduleArg);`, "the factory")

const result = await esbuild.build({
    stdin: { contents: source, resolveDir: ROOT, loader: "js" },
    bundle: true,
    write: false,
    format: "esm",
    target: "es2022",
    legalComments: "inline",
    // The glue names its own address to find its .wasm beside it. It never
    // looks, since oj always hands it the module, but the address must parse.
    define: { "import.meta.url": JSON.stringify("https://oj.invalid/xatlas/") },
})
const glue = result.outputFiles[0].text
if (glue.includes("binaryDecode('\\0asm")) throw new Error("the vendored glue still carries the module")
if (/\bimport\(/.test(glue)) throw new Error("the vendored glue still imports at runtime")

const header = `// Generated by scripts/vendor-xatlas.mjs from xatlas-wasm@${version} (MIT; xatlas, MIT). Do not edit.\n`
const out = path.join(ROOT, "src/light")
fs.writeFileSync(path.join(out, "xatlas.vendor.js"), header + "/* eslint-disable */\n// @ts-nocheck\n" + glue)
const wasmDir = path.join(ROOT, "assets/@ojplay/wasm")
fs.mkdirSync(wasmDir, { recursive: true })
for (const old of fs.readdirSync(wasmDir)) if (old.startsWith("xatlas-")) fs.rmSync(path.join(wasmDir, old))
fs.writeFileSync(path.join(wasmDir, `xatlas-${version}.wasm`), wasmBytes)
fs.writeFileSync(path.join(out, "xatlas.version.ts"), `${header.trim()}

/** The xatlas-wasm release oj runs. */
export const XATLAS_VERSION = ${JSON.stringify(version)}

/** The sha256 of the module, which a native link is checked against. */
export const XATLAS_WASM_SHA256 = ${JSON.stringify(sha256)}

/** What the module imports, as module and name: what a native link is made against. */
export const XATLAS_WASM_IMPORTS: readonly string[] = ${JSON.stringify(imports.map((i) => `${i.module}.${i.name}`), null, 4)}
`)
console.log(`vendored xatlas-wasm@${version}: glue ${glue.length} bytes, wasm ${wasmBytes.length} bytes, sha256 ${sha256}, ${imports.length} imports`)
